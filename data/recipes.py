# ==============================================================================
# 레시피 조합 및 조회 헬퍼 함수
# ==============================================================================
def resolve_recipe(
    base_recipe_id: str,
    toppings: Optional[Union[Iterable[str], str]] = None,
) -> str:
    """
    베이스 레시피 ID와 토핑 리스트를 받아 완성된 결과 recipe_id를 반환한다.
    - 토핑이 비어 있으면 base_recipe_id 그대로 반환한다.
    - 이미 토핑이 얹어진 레시피(예: 'skewer_spicy')에 추가 토핑('green_onion')을 넣어도
      누적 토핑 조합(['spicy_sauce', 'green_onion'])으로 정확히 판정한다.
    - 'skewer_greenonion'은 ['spicy_sauce', 'green_onion'] 또는 단일 ['green_onion'] 모두 매칭된다.
    """
    if not base_recipe_id or base_recipe_id not in RECIPES:
        return base_recipe_id

    if toppings is None:
        topping_list: List[str] = []
    elif isinstance(toppings, str):
        topping_list = [toppings] if toppings else []
    else:
        topping_list = [t for t in toppings if t]

    if not topping_list:
        return base_recipe_id

    current_recipe = RECIPES[base_recipe_id]
    root_base_id: str = current_recipe["base_recipe_id"]
    combined_toppings: Set[str] = set(current_recipe["required_toppings"]) | set(topping_list)

    # 동일 베이스를 공유하는 모든 레시피 후보 탐색
    for candidate_id, candidate in RECIPES.items():
        if candidate["base_recipe_id"] != root_base_id:
            continue
        req_set = set(candidate["required_toppings"])
        if req_set and req_set == combined_toppings:
            return candidate_id
        for alt in candidate.get("alternate_toppings", []):
            if set(alt) == combined_toppings or set(alt) == set(topping_list):
                return candidate_id

    # 새로 전달된 토핑 리스트만으로 매칭되는 경우도 확인
    new_toppings_set = set(topping_list)
    for candidate_id, candidate in RECIPES.items():
        if candidate["base_recipe_id"] != root_base_id:
            continue
        if set(candidate["required_toppings"]) == new_toppings_set and new_toppings_set:
            return candidate_id
        for alt in candidate.get("alternate_toppings", []):
            if set(alt) == new_toppings_set and new_toppings_set:
                return candidate_id

    return base_recipe_id


def can_add_topping(current_recipe_id: str, topping_id: str) -> bool:
    """현재 음식에 해당 토핑을 추가했을 때 유효한 상위 레시피로 변환되는지 여부를 반환한다."""
    if not current_recipe_id or current_recipe_id not in RECIPES:
        return False
    resolved = resolve_recipe(current_recipe_id, [topping_id])
    return resolved != current_recipe_id


def get_recipe(recipe_id: str) -> Optional[AttrDict]:
    """레시피 ID로 레시피 데이터를 반환한다."""
    return RECIPES.get(recipe_id)


def get_topping(topping_id: str) -> Optional[AttrDict]:
    """토핑 ID로 토핑 데이터를 반환한다."""
    return TOPPINGS.get(topping_id)


def get_recipes_by_country(country: str) -> List[AttrDict]:
    """특정 국가 코드('KR', 'JP', 'MX', 'TW')의 모든 레시피 리스트를 반환한다."""
    country_upper = country.upper()
    return [r for r in RECIPES.values() if r["country"] == country_upper]


def get_recipes_by_station(station_id: str, base_only: bool = False) -> List[AttrDict]:
    """특정 조리 기구(station_id)에서 만들 수 있는 레시피 리스트를 반환한다."""
    result = [r for r in RECIPES.values() if r["station_id"] == station_id]
    if base_only:
        result = [r for r in result if r["is_base"]]
    return result


def get_station_toppings(station_id: str) -> List[AttrDict]:
    """특정 조리 기구(station_id)에서 사용하는 토핑 데이터 리스트를 반환한다."""
    return [
        t for t in TOPPINGS.values() if station_id in t.get("station_ids", [])
    ]
