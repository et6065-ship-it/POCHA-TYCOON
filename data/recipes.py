# 레시피 데이터 정의 (RECIPES)
# ==============================================================================
def _make_recipe(
    recipe_id: str,
    name: str,
    country: str,
    station_id: str,
    slot_type: str,
    price: int,
    cook_time: float,
    burn_time: float,
    base_recipe_id: Optional[str] = None,
    required_toppings: Optional[List[str]] = None,
    alternate_toppings: Optional[List[List[str]]] = None,
    color: Tuple[int, int, int] = (235, 165, 75),
    secondary_color: Tuple[int, int, int] = (185, 105, 45),
    icon_shape: str = "round",
    description: str = "",
) -> AttrDict:
    toppings_list = list(required_toppings) if required_toppings else []
    resolved_base_id = base_recipe_id if base_recipe_id else recipe_id
    is_base = resolved_base_id == recipe_id and len(toppings_list) == 0
    can_burn = slot_type != "dispenser"

    return AttrDict(
        {
            "id": recipe_id,
            "recipe_id": recipe_id,
            "name": name,
            "country": country,
            "station_id": station_id,
            "station": station_id,
            "slot_type": slot_type,
            "station_type": slot_type,
            "category": slot_type,
            "price": price,
            "base_price": price,
            "cook_time": cook_time,
            "cooking_time": cook_time,
            "burn_time": burn_time,
            "can_burn": can_burn,
            "base_recipe_id": resolved_base_id,
            "base_id": resolved_base_id,
            "is_base": is_base,
            "required_toppings": toppings_list,
            "toppings": toppings_list,
            "has_topping": len(toppings_list) > 0,
            "alternate_toppings": alternate_toppings or [],
            "color": color,
            "secondary_color": secondary_color,
            "icon_shape": icon_shape,
            "description": description or f"{country} 대표 길거리 메뉴: {name}",
        }
    )


