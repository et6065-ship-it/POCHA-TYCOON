class AttrDict(dict):
    """
    딕셔너리 키 조회(d['key'])와 속성 조회(d.key)를 모두 지원하는 호환 딕셔너리.
    'id' 키가 존재하는 경우 문자열 ID와의 동등 비교(d == 'id_str') 및 딕셔너리 키 해싱도 지원한다.
    """

    def __getattr__(self, name: str) -> Any:
        try:
            return self[name]
        except KeyError as exc:
            raise AttributeError(f"'{type(self).__name__}' object has no attribute '{name}'") from exc

    def __setattr__(self, name: str, value: Any) -> None:
        self[name] = value

    def __hash__(self) -> int:  # type: ignore[override]
        if "id" in self:
            return hash(self["id"])
        return id(self)

    def __eq__(self, other: object) -> bool:
        if isinstance(other, str) and "id" in self:
            return str(self["id"]) == other
        return super().__eq__(other)


