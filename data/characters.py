CHARACTER_ORDER: List[str] = list(_RAW_CHARACTERS.keys())

CHARACTERS: Dict[str, AttrDict] = {}
for _cid, _cdata in _RAW_CHARACTERS.items():
    _passive = AttrDict(_cdata["passive"])
    _skill = AttrDict(_cdata["active_skill"])
    _wrapped = AttrDict(_cdata)
    _wrapped["passive"] = _passive
    _wrapped["active_skill"] = _skill
    _wrapped["skill"] = _skill  # 별칭 호환
    _wrapped["description"] = _cdata["passive_desc"]
    CHARACTERS[_cid] = _wrapped


def get_character(char_id: str) -> AttrDict:
    """주인공 ID로 캐릭터 데이터를 반환한다. 유효하지 않으면 기본 캐릭터(chef_kr)를 반환."""
    return CHARACTERS.get(char_id, CHARACTERS["chef_kr"])


def get_all_characters() -> List[AttrDict]:
    """정의된 순서대로 모든 주인공 데이터 리스트를 반환한다."""
    return [CHARACTERS[cid] for cid in CHARACTER_ORDER if cid in CHARACTERS]


def get_characters_by_country(country: str) -> List[AttrDict]:
    """특정 국가 코드('KR', 'TW', 'JP', 'MX', 'BR', 'RU', 'US', 'IN', 'CN') 또는 'ALL'의 캐릭터 리스트를 반환한다."""
    c_up = country.upper()
    if c_up == "ALL":
        return get_all_characters()
    return [CHARACTERS[cid] for cid in CHARACTER_ORDER if CHARACTERS[cid]["country"] == c_up]


def get_character_by_country(country: str) -> Optional[AttrDict]:
    """국가 코드에 해당하는 대표(첫 번째) 주인공 데이터를 반환한다."""
    chars = get_characters_by_country(country)
    return chars[0] if chars else None
